# shellcheck shell=sh
# Claude Code: CLAUDE.md imports AGENTS.md (Claude reads AGENTS.md only when there is no
# CLAUDE.md); hooks live in .claude/settings.local.json.
# shellcheck source=/dev/null
. "$(sdd_path agents/_hooks.sh)"

agent_sync() {
	need_jq
	if [ ! -f CLAUDE.md ]; then
		printf '@AGENTS.md\n' >CLAUDE.md
		exclude CLAUDE.md
		echo "created CLAUDE.md (imports AGENTS.md; kept out of git)"
	elif ! grep -qx '@AGENTS.md' CLAUDE.md; then
		printf '\n@AGENTS.md\n' >>CLAUDE.md
		echo "added @AGENTS.md to CLAUDE.md (commit this change)"
	fi
	merge_hooks .claude/settings.local.json claude
	ask_rules .claude/settings.local.json
	exclude .claude/settings.local.json
	echo "claude: session-start and stop hooks, and ask rules for approve, ship and tidy --remote, in .claude/settings.local.json"
	install_skills .claude/skills claude
	echo "claude: skills $NAME-new, -plan, -build, -review, -ship, -run in .claude/skills (all kept out of git)"
	subagent_hooks .claude/settings.local.json
	install_subagents .claude/agents
}

# install_subagents <dir>: one subagent <dir>/sdd-<role>.md per role (project [role] sections) whose
# tier's agent is claude, with that tier's model, kept out of git. A role subagent runs the item's
# next step, nothing else. Only files sdd made are replaced; ones for roles gone off claude go.
install_subagents() {
	mkdir -p "$1"
	for _old in "$1"/"$NAME"-*.md; do
		[ -f "$_old" ] && grep -q "^<!-- $NAME-managed:" "$_old" && rm -f "$_old"
	done
	_n=0
	for _role in $(git config -f "$SDD_HOME/config" --get-regexp '^role\..*\.tier$' 2>/dev/null | sed 's/^role\.\(.*\)\.tier .*/\1/'); do
		case $_role in *[!a-z0-9-]*) warn "skipped role $_role: role names are lowercase words"; continue ;; esac
		_tier=$(cfg "role.$_role.tier")
		[ "$(tier_get "$_tier" agent)" = claude ] || continue
		_model=$(tier_get "$_tier" model)
		tier_ok claude "$_model" || { warn "skipped role $_role: tier $_tier needs a model name without spaces or quotes"; continue; }
		_f="$1/$NAME-$_role.md"
		if [ -f "$_f" ]; then warn "left $_f alone: it was not made by $NAME"; continue; fi
		{
			printf -- '---\nname: %s-%s\n' "$NAME" "$_role"
			printf 'description: The %s for one %s item: runs `%s next` and does that step. Use when asked to run the %s on an item (the %s-run skill).\n' "$_role" "$NAME" "$CMD" "$_role" "$NAME"
			printf 'model: %s\n---\n' "$_model"
			printf '<!-- %s-managed: generated by `%s sync`; edits are overwritten -->\n' "$NAME" "$CMD"
			printf 'You are the %s for an item in this repo. Run `%s next`, do exactly the step it gives you\n' "$_role" "$CMD"
			printf 'and nothing else, then report in a few lines what you did and what is left.\n'
			# A subagent serves whichever item it is given: {{id}} reads "the given item".
			if _rp=$(sdd_path "prompts/role-$_role.md"); then echo; render "$_rp" 'the given item' '' ''; fi
		} >"$_f"
		exclude "$_f"
		_n=$((_n + 1))
	done
	[ "$_n" -eq 0 ] || echo "claude: $_n role subagent(s) in $1 ($NAME-<role>.md, kept out of git)"
}

# subagent_hooks <settings>: SubagentStart and SubagentStop hooks for the role subagents, so
# every role run is logged with its tokens (FR-16.6); keeps everything else.
subagent_hooks() {
	if ! jq --arg st "$(hook_cmd subagent-start claude)" --arg sp "$(hook_cmd subagent-stop claude)" --arg tag "$NAME-managed" --arg m "$NAME-.*" '
		def clean: map(.hooks |= map(select((.command // "") | contains($tag) | not))) | map(select((.hooks | length) > 0));
		.hooks.SubagentStart = (((.hooks.SubagentStart // []) | clean) + [{matcher: $m, hooks: [{type: "command", command: $st}]}])
		| .hooks.SubagentStop = (((.hooks.SubagentStop // []) | clean) + [{matcher: $m, hooks: [{type: "command", command: $sp}]}])
	' "$1" >"$1.tmp.$$"; then
		rm -f "$1.tmp.$$"
		die "could not update $1 (is it valid JSON?)"
	fi
	mv "$1.tmp.$$" "$1"
}

# ask_rules <settings>: Claude Code asks the human before approve, ship or tidy --remote runs.
# Covers the spellings agents use (relative, ./, sh or bash, this checkout's absolute path,
# and the bare name for a symlink on PATH); a relative path from a subfolder
# (../.sdd/bin/sdd) is not.
# Replaces exactly these entries, keeping the user's own rules.
ask_rules() {
	jq --arg cmd "$CMD" --arg root "$ROOT" --arg name "$NAME" '
		([$cmd, "./" + $cmd, "sh " + $cmd, "bash " + $cmd, $root + "/" + $cmd, $name]
			| map(. as $c | ["approve", "ship", "tidy --remote"] | map("Bash(" + $c + " " + . + ":*)")) | flatten) as $add
		| .permissions = (.permissions // {})
		| .permissions.ask = (((.permissions.ask // []) - $add) + $add)
	' "$1" >"$1.tmp.$$" || { rm -f "$1.tmp.$$"; die "could not update $1"; }
	mv "$1.tmp.$$" "$1"
}

# agent_usage <output file>: "<tokens in>\t<tokens out>\t<cost>\t<verdict>" from the result line
# of `claude -p --output-format json`. Tokens in count cached input too (what was processed).
agent_usage() {
	_l=$(grep '"type":"result"' "$1" 2>/dev/null | tail -n 1)
	[ -n "$_l" ] || { printf '\t\t\tno result\n'; return 0; }
	_a=$(json_num input_tokens "$_l") _b=$(json_num cache_creation_input_tokens "$_l") _c=$(json_num cache_read_input_tokens "$_l")
	_in=$((${_a:-0} + ${_b:-0} + ${_c:-0}))
	_v=ok
	case $_l in *'"is_error":true'*) _v=$(json_str subtype "$_l") ;; esac
	printf '%s\t%s\t%s\t%s\n' "$_in" "$(json_num output_tokens "$_l")" "$(json_num total_cost_usd "$_l")" "${_v:-error}"
}

# agent_transcript_usage <subagent transcript>: "<tokens in>\t<tokens out>\t<model>", summed over
# its assistant messages, each message once (parallel tool calls repeat one message; the largest
# output count is the final one). The transcript layout is Claude Code's own (kb/claude-subagents.md).
agent_transcript_usage() {
	need_jq
	jq -rs '[.[] | select(.message.usage? != null) | {id: .message.id, model: .message.model, u: .message.usage}]
		| group_by(.id) | map(max_by(.u.output_tokens // 0))
		| [ (map((.u.input_tokens // 0) + (.u.cache_creation_input_tokens // 0) + (.u.cache_read_input_tokens // 0)) | add // 0),
		    (map(.u.output_tokens // 0) | add // 0),
		    (map(.model) | map(select(. != null)) | first // "") ] | @tsv' "$1"
}

# agent_run <bin> <model> <prompt file> <output file> <args>: one headless run, the prompt on
# stdin. Only the tier's args are added (no permission flags of sdd's own; design §13).
agent_run() {
	# shellcheck disable=SC2086 # the tier's args are the developer's words, split on purpose
	"$1" -p --output-format json --model "$2" $5 <"$3" >"$4"
}

# agent_subagent_hook <subagent-start|subagent-stop> <hook JSON>: log a role subagent's run
# (sdd-<role>): note its start, and at its stop sum its transcript (no hook reports tokens).
agent_subagent_hook() {
	command -v jq >/dev/null 2>&1 && [ -n "$2" ] || return 0
	_type=$(printf '%s' "$2" | jq -r '.agent_type // empty')
	_aid=$(printf '%s' "$2" | jq -r '.agent_id // empty')
	_role=${_type#"$NAME"-}
	[ "$_role" != "$_type" ] || return 0
	case $_role in '' | *[!a-z0-9-]*) return 0 ;; esac
	case $_aid in '' | *[!A-Za-z0-9_-]*) return 0 ;; esac
	mkdir -p "$ST/runs"
	_mark="$ST/runs/sub.$_aid"
	if [ "$1" = subagent-start ]; then
		_item=- _phase=- TASK=
		if current_item; then
			_item=$ID
			item_phase
			_phase=$PHASE
		fi
		printf '%s\t%s\t%s\t%s\t%s\n' "$(date +%s)" "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$_item" "$_phase" "$TASK" >"$_mark"
		return 0
	fi
	_st=$(cat "$_mark" 2>/dev/null)
	rm -f "$_mark"
	[ -n "$_st" ] || _st=$(printf '%s\t%s\t-\t-\t' "$(date +%s)" "$(date -u +%Y-%m-%dT%H:%M:%SZ)")
	_tr=$(printf '%s' "$2" | jq -r '.agent_transcript_path // empty')
	_use=
	[ -f "$_tr" ] && _use=$(agent_transcript_usage "$_tr" 2>/dev/null)
	_v='done'
	[ -n "$_use" ] || _v="no transcript"
	run_slot
	[ -z "$_tr" ] || printf '%s\n' "$_tr" >"$RUNDIR/transcript"
	run_log "$RUN" "$(tsv 2 "$_st")" "$(tsv 3 "$_st")" "$_role" claude "$(tsv 3 "$_use")" "$(tsv 4 "$_st")" "$(tsv 5 "$_st")" \
		"$(tsv 1 "$_use")" "$(tsv 2 "$_use")" "" "$(($(date +%s) - $(tsv 1 "$_st")))" 0 "$_v" >/dev/null
}
